#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = 'server/_shared/prediction-edge.generated.mjs';
const TYPES = 'server/_shared/prediction-edge.generated.d.mts';
const BANNER = '// Generated by scripts/generate-prediction-edge.mjs. Do not edit.\n'
  + '// Canonical algorithms: scripts/_prediction-classify.mjs and _prediction-upstream.mjs.\n';
const DECLARATION = `${BANNER}
export type PredictionCategory = 'geopolitical' | 'tech' | 'finance';
export interface PredictionMarketRecord {
  title: string;
  yesPrice: number;
  volume: number;
  url: string;
  endDate?: string;
  source?: string;
  tags?: string[];
  [key: string]: unknown;
}
export function buildBootstrapPools<T extends PredictionMarketRecord>(
  markets: T[], options?: { limit?: number; now?: number },
): {
  pools: Record<PredictionCategory, Array<T & { regions: string[] }>>;
  classified: Record<PredictionCategory, number>;
  duplicatesDropped: number;
};
export function fetchPolymarketEventsByTag(
  tag: string, options: {
    fetchFn?: typeof fetch;
    baseUrl: string;
    userAgent: string;
    timeoutMs?: number;
    limit?: number;
    now?: Date;
  },
): Promise<unknown[]>;
`;

export async function renderPredictionEdge() {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: ['server/_shared/prediction-edge.entry.mjs'],
    outfile: OUTPUT,
    bundle: true,
    write: false,
    platform: 'browser',
    format: 'esm',
    target: 'es2020',
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: BANNER.trimEnd() },
    metafile: true,
    logLevel: 'silent',
  });
  const code = result.outputFiles[0].text;
  if (Object.values(result.metafile.outputs).some((output) => output.imports.length)) {
    throw new Error('Prediction Edge artifact must be self-contained');
  }
  if (/\b(?:with|assert)\s*\{\s*type\s*:/.test(code) || /\b(?:require\s*\(|node:)/.test(code)) {
    throw new Error('Prediction Edge artifact contains unsupported imports');
  }
  return new Map([[OUTPUT, code], [TYPES, DECLARATION]]);
}

export async function generatePredictionEdge({ check = false } = {}) {
  const files = await renderPredictionEdge();
  for (const [path, content] of files) {
    const target = resolve(ROOT, path);
    if (check) {
      let current;
      try { current = readFileSync(target, 'utf8'); } catch { /* reported as stale below */ }
      if (current !== content) throw new Error(`${path} is stale; run npm run predictions:edge:generate`);
    } else writeFileSync(target, content);
  }
  return [...files.keys()];
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const files = await generatePredictionEdge({ check: process.argv.includes('--check') });
    console.log(`Prediction Edge artifact ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${files.join(', ')}`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
